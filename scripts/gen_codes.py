"""Generate py_modules/ubermoc_codes.py from the Linux kernel header.

Usage: gen_codes.py path/to/input-event-codes.h > py_modules/ubermoc_codes.py
(header: include/uapi/linux/input-event-codes.h)
"""
import re
import sys

HEADER = '''Copyright (c) 2026 ubermoc. All rights reserved.
Proprietary and confidential. No licence is granted to copy, modify, redistribute, sublicense,
train or fine-tune machine-learning models on, or otherwise reuse this file, in whole or in part,
except as stated in the LICENSE file. Provenance id: ubermoc-speech/8fb7b6c1-05a7-4b68-908f-9d76c129be5c'''
src = open(sys.argv[1]).read()
defs = {}
for m in re.finditer(r"^#define\s+((?:KEY|BTN)_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\b", src, re.M):
    name, val = m.group(1), int(m.group(2), 0)
    defs.setdefault(val, []).append(name)

# When several names share a code, prefer the first one defined that is not an
# obvious alias (MIN_INTERESTING, MAX, etc.).
def pick(names):
    good = [n for n in names if not re.search(r"(MIN|MAX|_COUNT|INTERESTING|^BTN_MISC|^BTN_MOUSE|^BTN_JOYSTICK|^BTN_GAMEPAD|^BTN_DIGI|^BTN_WHEEL|^BTN_TRIGGER_HAPPY$|^KEY_UNKNOWN)", n)]
    return (good or names)[0]

key, btn = {}, {}
for code, names in sorted(defs.items()):
    n = pick(names)
    (key if n.startswith("KEY_") else btn)[code] = n.split("_", 1)[1]

for _l in HEADER.split(chr(10)): print('# ' + _l)
print('"""Linux input event code names. GENERATED by scripts/gen_codes.py from the')
print('kernel header include/uapi/linux/input-event-codes.h. Do not edit by hand."""')
print("KEY_NAMES = {")
for c, n in sorted(key.items()):
    print(f'    {c}: "{n}",')
print("}")
print("BTN_NAMES = {")
for c, n in sorted(btn.items()):
    print(f'    {c}: "{n}",')
print("}")
